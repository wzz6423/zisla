    @Test(arguments: regionalExamples)
    func regionalFixedAndMobilePhonesReachThePublicEntry(_ sample: RegionExample) throws {
        for (text, expected) in [(sample.fixed, sample.fixedE164), (sample.mobile, sample.mobileE164),
                                 (sample.fixedE164, sample.fixedE164), (sample.mobileE164, sample.mobileE164)] {
            let result = try #require(detect(text, country: sample.country), "\(sample.country): \(text)")
            #expect(result.kind == .phone, "\(sample.country): \(text)")
            #expect(result.actions == [.callPhone(expected)])
            #expect(result.title == text)
            #expect(result.actions.allSatisfy { $0.kind != .openURL })
        }
    }

    @Test(arguments: regionalExamples)
    func representativeBareNumbersRemainDialable(_ sample: RegionExample) {
        for (text, expected) in [(sample.fixed, sample.fixedE164), (sample.mobile, sample.mobileE164)] {
            let bare = text.filter(\.isNumber)
            #expect(detect(bare, country: sample.country)?.action == .callPhone(expected), "\(sample.country): \(bare)")
        }
    }

