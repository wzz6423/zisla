    @Test func seededUnsafeMutationsCannotBecomeDialActions() {
        var seed: UInt64 = 0x50484F4E
        let invalid = Array("&?;=/\\\u{0}\u{202E}\u{2066}Ω²\n")
        for index in 0..<160 {
            seed = seed &* 6_364_136_223_846_793_005 &+ 1
            var value = Array("+12015550123")
            value.insert(invalid[Int((seed >> 32) % UInt64(invalid.count))], at: 2 + Int(seed % 8))
            #expect(detect(String(value), country: "US", kinds: [.phone]) == nil, "seed 50484F4E, case \(index)")
        }
        #expect(detect("Phone: +" + String(repeating: "1", count: 4_097), country: "US", kinds: [.phone]) == nil)
        #expect(detect("Phone:" + String(repeating: " ", count: 129) + "+12015550123", country: "US", kinds: [.phone]) == nil)
    }

    private func detect(_ text: String, country: String?, locale: Locale = Locale(identifier: "en_US"),
                        kinds: Set<ClipboardAssistantKind> = Set(ClipboardAssistantKind.allCases)) -> ClipboardAssistantDetection? {
        ClipboardAssistantDetector.detect(text: text, enabledKinds: kinds, systemLanguageIdentifier: "en",
            now: Date(timeIntervalSince1970: 1_790_035_200), timeZone: TimeZone(secondsFromGMT: 0)!,
            locale: locale, countryCode: country)
    }

